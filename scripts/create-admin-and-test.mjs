import { PrismaClient } from '@prisma/client';
import bcrypt from 'bcryptjs';

const prisma = new PrismaClient();

const ADMIN_EMAIL = process.env.ADMIN_EMAIL || 'admin@3yeses.test';
const ADMIN_PASSWORD = process.env.ADMIN_PASSWORD || 'Admin1234!';
const TEST_EMAIL = process.env.TEST_EMAIL || 'test@3yeses.test';
const TEST_PASSWORD = process.env.TEST_PASSWORD || 'Test1234!';

async function upsertAdmin(){
  const hash = await bcrypt.hash(ADMIN_PASSWORD, 10);
  const id = process.env.ADMIN_ID || 'admin';

  const user = await prisma.user.upsert({
    where: { email: ADMIN_EMAIL },
    update: { password: hash, role: 'ADMIN', name: 'Administrator' },
    create: {
      id,
      email: ADMIN_EMAIL,
      password: hash,
      role: 'ADMIN',
      name: 'Administrator',
    }
  });

  return { user, password: ADMIN_PASSWORD };
}

async function upsertTest(){
  const hash = await bcrypt.hash(TEST_PASSWORD, 10);
  const id = process.env.TEST_ID || 'test-user';

  const user = await prisma.user.upsert({
    where: { email: TEST_EMAIL },
    update: { password: hash, role: 'TALENT', name: 'Test User' },
    create: {
      id,
      email: TEST_EMAIL,
      password: hash,
      role: 'TALENT',
      name: 'Test User',
    }
  });

  // Create a minimal TalentProfile if missing
  await prisma.talentProfile.upsert({
    where: { userId: user.id },
    update: {},
    create: {
      userId: user.id,
      bio: 'Test account profile generated by script.',
      location: 'Remote',
      skills: ['Test Skill'],
      profileComplete: true
    }
  });

  return { user, password: TEST_PASSWORD };
}

async function main(){
  console.log('Creating admin and test accounts (upsert, idempotent)...');
  const admin = await upsertAdmin();
  console.log('Admin:', admin.user.email, 'id=', admin.user.id);
  const test = await upsertTest();
  console.log('Test user:', test.user.email, 'id=', test.user.id);

  console.log('\nCredentials:');
  console.log(`Admin -> email: ${admin.user.email}  password: ${admin.password}`);
  console.log(`Test  -> email: ${test.user.email}  password: ${test.password}`);

  // Show counts
  const uCount = await prisma.user.count();
  const pCount = await prisma.talentProfile.count();
  console.log(`\nTotal users: ${uCount}, TalentProfiles: ${pCount}`);
}

main()
  .catch((e)=>{ console.error(e); process.exitCode = 1; })
  .finally(async()=>{ await prisma.$disconnect(); });
